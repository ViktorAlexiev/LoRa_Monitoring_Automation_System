#include "aes128.h"
#include <cstdio>
#include <cstring>

int main() {
  // FIPS-197 Appendix B официален тестов вектор
  uint8_t key[16] = {0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f};
  uint8_t pt[16]  = {0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff};
  uint8_t expected[16] = {0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a};
  uint8_t out[16];

  aes128::AES128 aes;
  aes.setKey(key);
  aes.encryptBlock(out, pt);

  bool ok = memcmp(out, expected, 16) == 0;
  printf("AES-128 FIPS-197 Appendix B vector: %s\n", ok ? "PASS" : "FAIL");
  printf("  got:      ");
  for (int i=0;i<16;i++) printf("%02x", out[i]);
  printf("\n  expected: ");
  for (int i=0;i<16;i++) printf("%02x", expected[i]);
  printf("\n");
  return ok ? 0 : 1;
}
