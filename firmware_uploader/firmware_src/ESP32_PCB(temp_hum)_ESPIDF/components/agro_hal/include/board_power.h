/*
  board_power.h - захранване на платката: load switch на ИНТЕРФЕЙСИТЕ (сензори, консуматори) и на ДЕЛИТЕЛЯ за
  батерията + измерване на батерията.
  ---------------------------------------------------------------------------------------
  Двата ключа са отделни GPIO изходи (пиновете са в board_pins.h, ВРЕМЕННИ). HIGH = включен.
  Политика по устройство (решава се от app_main):
    gateway, repeater : интерфейсният ключ е ИЗКЛЮЧЕН (нищо не е закачено към него)
    executor          : включва се в началото и остава включен
    sensor            : изключен; включва се само за измерването (+ пауза за събуждане на сензорите)
  Делителят за батерията се включва САМО докато трае измерването (иначе тегли постоянен ток през резисторите).
*/
#ifndef BOARD_POWER_H
#define BOARD_POWER_H

#include <stdint.h>
#include <stdbool.h>

// "няма измерване" на батерията: същото число като SENSOR_RAW_NODATA/BATTERY_RAW_NODATA в protocol.h (най-малкото int16)
#define BOARD_BATTERY_NODATA  INT16_MIN

// Освобождава заключените пинове (след дълбок сън) и ги конфигурира като изходи със ВСИЧКО ИЗКЛЮЧЕНО.
// Вика се първо в app_main на всяко приложение.
void board_power_init(void);

// Load switch на интерфейсите (сензори, консуматори). true = включен.
void board_iface_power(bool on);
bool board_iface_is_on(void);

// Напрежението на батерията в mV: включва делителя, изчаква да се стабилизира, чете АЦП (усреднено, калибрирано),
// изключва делителя. BOARD_BATTERY_NODATA при грешка или стойност извън 2000..4600 mV (напр. няма батерия).
// Блокира ~20-30 ms - вика се когато радиото е в покой (не между CAD и предаване).
int16_t board_battery_mv(void);

// Преди дълбок сън: заключва нивата на двата управляващи пина, за да остане ключът изключен (иначе пинът "плава").
// Препоръка: и външен pull резистор на гейта на ключа. Състоянието се освобождава от board_power_init() след събуждане.
void board_power_hold_for_deep_sleep(void);

#endif
